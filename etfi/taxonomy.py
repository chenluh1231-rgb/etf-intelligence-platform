def _hit(text: str, kws) -> list[str]:
    return [k for k in kws if k in text]


def classify(name: str, index_name: str = "", ftype: str = "") -> dict:
    """把一只 ETF 映射为结构化特征。全部规则可追溯。"""
    t = f"{name} {index_name or ''}"
    t_up = t.upper()

    asset_class, market = "境内股票", "A股"
    layer = "宽基"

    if any(k in t for k in CURRENCY_KW):
        return _pack("货币", "货币", "现金", [], [], [], [], name, index_name)

    if any(k in t for k in BOND_KW):
        return _pack("债券", "债券", "债券", [], [], [], [], name, index_name)

    if any(k in t for k in COMMODITY_KW) and not any(k in t for k in COMMODITY_EXCLUDE):
        return _pack("商品", "商品", "商品", [], ["大宗商品"], [], [], name, index_name)

    for mk, kws in CROSS_KW.items():
        if any(k in t for k in kws):
            asset_class, market = "境外股票", mk
            break

    sectors, themes, styles = [], [], []
    for sec, kws in SECTOR_KW.items():
        if any(k in t for k in kws):
            sectors.append(sec)
    for th, kws in THEME_KW.items():
        if any(k in t for k in kws):
            themes.append(th)
    for st, kws in STYLE_KW.items():
        if any(k in t for k in kws):
            styles.append(st)

    is_broad = any(k in t for k in BROAD_KW)
    if sectors or themes:
        layer = "行业主题"
    elif styles:
        layer = "策略因子"
    elif is_broad:
        layer = "宽基"
    else:
        layer = "宽基" if market == "A股" else "境外宽基"

    if market != "A股" and layer == "宽基":
        layer = "境外宽基"

    size_style = None
    for sz, kws in SIZE_STYLE_KW.items():
        if any(k in t for k in kws):
            size_style = sz
            break

    leveraged = any(k in t for k in LEVERAGE_KW) or bool(re.search(r"\d倍", t))

    return _pack(asset_class, layer, market, sectors, themes, styles,
                 [size_style] if size_style else [], name, index_name, leveraged)


def _pack(asset_class, layer, market, sectors, themes, styles, size_style,
          name="", index_name="", leveraged=False) -> dict:
    return {
        "asset_class": asset_class,
        "layer": layer,
        "market": market,
        "sectors": sectors,
        "themes": themes,
        "styles": styles,
        "size_style": size_style,
        "name": name,
        "index_name": index_name,
        "leveraged": leveraged,
        "tags": sorted(set(sectors + themes + styles)),
    }


