  function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"']/g,
      (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  }

  /* 生成带角标的术语；没有收录时原样返回，不显示角标 */
  function term(label, key) {
    const k = key || label;
    const t = T[k];
    if (!t) return esc(label);
    const body = (s) => esc(s).replace(/\n/g, '<br>');
    return '<span class="tipwrap">' + esc(label)
      + '<sup class="ti" aria-label="名词解释">i</sup>'
      + '<span class="tipb" role="tooltip"><b>' + esc(k) + '</b>'
      + '<p>' + body(t.d) + '</p>'
      + '<p class="tf">算法：' + body(t.f) + '</p>'
      + (t.l ? '<p class="tl">口径与限制：' + body(t.l) + '</p>' : '')
      + '</span></span>';
  }

